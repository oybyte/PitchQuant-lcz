def stat(label, rows):
    n = len(rows)
    h = sum(1 for _,x,y in rows if x>y); d = sum(1 for _,x,y in rows if x==y); a = sum(1 for _,x,y in rows if y>x)
    over = sum(1 for _,x,y in rows if x+y > 2.5)
